# Builds firmware/kiosk_screen/ui_fonts.h: anti-aliased (4-bit alpha) bitmap fonts for the kiosk renderer,
# cut from the same variable fonts the web uses (web/public/kiosk/fonts): Bricolage Grotesque (headings),
# Archivo (numbers, condensed) and Atkinson Hyperlegible Next (body).
#
# Run from the repo root (needs uv; it fetches Pillow + fontTools on the fly):
#   uv run --no-project --with pillow --with fonttools --with brotli python -I firmware/tools/mkfonts.py
#
# Format (see ui_draw.h): per font a dense glyph table for code points first..last and one nibble stream.
# A glyph is w x h nibbles (high nibble first), placed at (cursor_x + xo, baseline + yo).
import io
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "web", "public", "kiosk", "fonts")
OUT = os.path.join(ROOT, "firmware", "kiosk_screen", "ui_fonts.h")

ASCII = "".join(chr(c) for c in range(32, 127))
LATIN1 = ASCII + "".join(chr(c) for c in range(0xA0, 0x100))
NUMS = " 0123456789$%.,+-:/<>¢'"

# name, file, axes, px size, charset
FONTS = [
    ("F_HERO", "bricolage-grotesque-latin", {"wght": 800, "wdth": 100, "opsz": 96}, 96, ASCII),
    ("F_H1", "bricolage-grotesque-latin", {"wght": 800, "wdth": 100, "opsz": 44}, 44, LATIN1),
    ("F_H2", "bricolage-grotesque-latin", {"wght": 800, "wdth": 100, "opsz": 32}, 31, LATIN1),
    ("F_H3", "bricolage-grotesque-latin", {"wght": 700, "wdth": 100, "opsz": 24}, 24, LATIN1),
    ("F_B1", "atkinson-hyperlegible-next-latin", {"wght": 700}, 20, LATIN1),
    ("F_B2", "atkinson-hyperlegible-next-latin", {"wght": 400}, 18, LATIN1),
    ("F_B3", "atkinson-hyperlegible-next-latin", {"wght": 600}, 15, LATIN1),
    ("F_N1", "archivo-latin-wdth", {"wght": 800, "wdth": 75}, 92, NUMS),
    ("F_N2", "archivo-latin-wdth", {"wght": 800, "wdth": 75}, 60, NUMS),
    ("F_N3", "archivo-latin-wdth", {"wght": 800, "wdth": 82}, 32, ASCII + "¢"),
    ("F_N4", "archivo-latin-wdth", {"wght": 700, "wdth": 90}, 21, ASCII + "¢"),
]


def load(file, axes, size):
    tt = TTFont(os.path.join(SRC, file + ".woff2"))
    tt.flavor = None
    have = {a.axisTag: (a.minValue, a.maxValue) for a in tt["fvar"].axes}
    loc = {k: max(have[k][0], min(have[k][1], v)) for k, v in axes.items() if k in have}
    static = instancer.instantiateVariableFont(tt, loc)
    buf = io.BytesIO()
    static.save(buf)
    buf.seek(0)
    return ImageFont.truetype(buf, size)


def build(name, file, axes, size, chars):
    font = load(file, axes, size)
    ascent, descent = font.getmetrics()
    first, last = min(ord(c) for c in chars), max(ord(c) for c in chars)
    glyphs, data = [], bytearray()
    pad = size
    for cp in range(first, last + 1):
        ch = chr(cp)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = int(round(font.getlength(ch)))
        img = Image.new("L", (size * 3 + pad * 2, size * 3), 0)
        d = ImageDraw.Draw(img)
        base = size * 2
        d.text((pad, base), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if not box:
            glyphs.append((len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        w, h = crop.size
        px = list(crop.getdata())
        nib = [(v * 15 + 127) // 255 for v in px]
        if len(nib) % 2:
            nib.append(0)
        off = len(data)
        for i in range(0, len(nib), 2):
            data.append((nib[i] << 4) | nib[i + 1])
        glyphs.append((off, w, h, x0 - pad, y0 - base, adv))
    return {
        "name": name, "first": first, "last": last, "ascent": ascent, "descent": descent,
        "glyphs": glyphs, "data": data, "size": size,
    }


def main():
    fonts = [build(*f) for f in FONTS]
    out = [
        "// Generated by firmware/tools/mkfonts.py from web/public/kiosk/fonts. Do not edit by hand.",
        "// 4-bit anti-aliased glyphs: Bricolage Grotesque (F_HERO, F_H*), Atkinson Hyperlegible Next (F_B*),",
        "// Archivo condensed (F_N*). SIL Open Font License 1.1 (see the font projects).",
        "#pragma once",
        '#include "ui_draw.h"',
        "",
    ]
    total = 0
    for f in fonts:
        n = f["name"]
        total += len(f["data"]) + len(f["glyphs"]) * 8
        out.append(f"static const uint8_t {n}_bits[] = {{")
        d = f["data"]
        for i in range(0, len(d), 32):
            out.append("  " + ",".join(str(b) for b in d[i:i + 32]) + ",")
        if not d:
            out.append("  0")
        out.append("};")
        out.append(f"static const HGlyph {n}_glyphs[] = {{")
        for g in f["glyphs"]:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(
            f"static const HFont {n} = {{{n}_bits, {n}_glyphs, {f['first']}, {f['last']}, {f['ascent']}, {f['descent']}, {f['size']}}};"
        )
        out.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}: {len(fonts)} fonts, {total / 1024:.0f} KB of font data")
    for f in fonts:
        print(f"  {f['name']}: {f['size']}px asc {f['ascent']} desc {f['descent']} {len(f['data']) / 1024:.1f} KB")


if __name__ == "__main__":
    sys.exit(main())
